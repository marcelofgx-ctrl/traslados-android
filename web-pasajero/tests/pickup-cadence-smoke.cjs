"use strict";
const {strict:assert}=require("node:assert");
const {readFileSync}=require("node:fs");
const {runInNewContext}=require("node:vm");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const js=readFileSync(path.join(root,"pickup-cadence.js"),"utf8");
const index=readFileSync(path.join(root,"index.html"),"utf8");
const sw=readFileSync(path.join(root,"sw.js"),"utf8");
const scope={window:{}};
runInNewContext(js,scope);
const p=scope.window.TrasladosPickupCadence;
assert(Object.isFrozen(p));
assert.equal(p.intervalMs("moving"),25000);
assert.equal(p.intervalMs("stationary"),45000);
assert.equal(p.intervalMs("missing"),45000);
assert.equal(p.arrivalLabel(5),"Hasta 5 min");
assert.equal(p.arrivalLabel(10),"5–10 min");
assert.equal(p.arrivalLabel(15),"10–15 min");
assert.equal(p.arrivalLabel(null),"Por confirmar");
assert(index.indexOf("pickup-cadence.js")<index.indexOf("app.js?v=42"));
assert(sw.includes("pickup-cadence.js")&&sw.includes("traslados-cliente-pwa-v42"));
console.log("PASS pickup cadence 25/45s, honest five-minute ranges and offline PWA v40");
