"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const window={};
const src=fs.readFileSync(path.join(__dirname,"../premium-map.js"),"utf8");
vm.runInNewContext(src,{window,document:{}},{timeout:2000});
const map=window.TrasladosPremiumMap;
assert(map&&typeof map.layout==="function"&&typeof map.render==="function");
const A=[-34.923,-56.162],B=[-34.830,-56.026];
assert.equal(map.project(A).length,2);
assert.equal(map.project([-95,-56]),null);
assert.equal(map.project(["bad",-56]),null);
assert.equal(map.layout([A],360,232),null);
assert.equal(map.layout([A,[-34.823,200]],360,232),null);
const view=map.layout([A,[-34.91,-56.14],[-34.86,-56.09],B],360,232);
assert(view&&view.zoom>=8&&view.zoom<=15);
assert.equal(view.points.length,4);
assert(view.points.every(([x,y])=>Number.isFinite(x)&&Number.isFinite(y)));
assert(Math.abs(view.points[0][0]-view.points.at(-1)[0])>1);
assert.equal(view.width,360);
console.log("PASS map geometry: mercator, inputs, encuadre; datos reales solo tras verificación");
