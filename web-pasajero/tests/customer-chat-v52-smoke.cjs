"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,".."),read=n=>fs.readFileSync(path.join(root,n),"utf8");
const app=read("app.js"),html=read("index.html"),sw=read("sw.js"),css=read("styles.css");
const win={};vm.runInNewContext(read("trip-board.js"),{window:win,Map,Set,Date,Number,Array,String});
const model=win.TrasladosTripBoard;
const base={id:"id1",code:"TR-ONE",status:"ACEPTADA",pickup_date:"2026-10-23",quote_status:"ACEPTADO",last_driver_message_id:14};
const next={...base,last_driver_message_id:15};
const ss=model.snapshot([base]);
const changed=model.notifications(ss,[next]);
assert.equal(changed.length,1,"Driver message must be detected by ID");
assert.equal(changed[0].kind,"message");
assert.equal(model.notifications(ss,[base]).length,0,"Unchanged refresh must be quiet");
assert.equal(model.notifications(null,[next]).length,0,"Fresh load must be baseline");
assert.equal(model.notifications(model.snapshot([next]),[next]).length,0,"Do not re-notify same message");
assert(html.includes('id="trips-alert-sound"')&&html.includes('id="trips-alert-vibrate"'));
assert(html.includes('trip-board.js?v=6')&&html.includes('app.js?v=71')&&html.includes('styles.css?v=71'));
assert(sw.includes("traslados-cliente-pwa-v71"));
assert(app.includes('rpc("customer_list_reservations_v15"'));
assert(app.includes('rpc("get_reservation_by_token_v4"'));
assert(app.includes('rpc("customer_trip_chat_v1"'));
assert(app.includes('rpc("customer_trip_chat_send_v1"'));
assert(app.includes('newClientRequestId()'));
assert(app.includes('tripChatAttempts.set(key,{body,id:requestId})'));
assert(app.includes('if(!response?.id)throw'));
assert(app.includes('function playTripAlertSound()'));
assert(app.includes('if(!$("trips-alert-sound").checked||!tripAlertAudio'));
assert(app.includes('function showTripNotice(change)')&&app.includes('message?"Nuevo mensaje del conductor"'));
assert(app.includes('if($("trips-alert-vibrate").checked&&navigator.vibrate)'));
assert(app.includes('text(bubble,"span",item.body||"")'),"No HTML injection in messages");
assert(app.includes('id===activeTripChat.id'),"Chat survives background refresh without losing its reservation");
assert(html.includes('id="trip-chat-sheet"')&&app.includes('function closeTripChat()'),
  "Chat must open in a dedicated closable screen");
assert(css.includes('.trip-chat-bubble.from-customer')&&css.includes('.trip-chat-send'));
console.log("PASS v52 customer chat, sound/vibration consent and no repeated message alerts");
