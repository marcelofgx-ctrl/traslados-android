"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const path=require("node:path");
const root=path.join(__dirname,"..");
const source=fs.readFileSync(path.join(root,"guest-history.js"),"utf8");
const sandbox={window:{}};
vm.runInNewContext(source,sandbox);
const merge=sandbox.window.TrasladosGuestHistory.merge;
assert.equal(typeof merge,"function");
const receipts=[{token:"authorized-guest-token"},{token:"second-guest-token"}];
const fulfilled=(value)=>({status:"fulfilled",value});
const existing={id:"account-a",status:"ACEPTADA",source:"session"};
const guest={id:"guest-b",status:"PENDIENTE"};
let union=merge([existing],receipts,[fulfilled(guest),{status:"rejected",reason:new Error("offline")}]);
assert.equal(union.length,2);
assert.equal(union[0].id,"account-a");
assert.equal(union[1].id,"guest-b");
assert.equal(union[1].__guestToken,"authorized-guest-token");
assert.equal(union[1].status,"PENDIENTE");
union=merge([existing],receipts,[fulfilled({id:"account-a",status:"PENDIENTE"}),fulfilled({id:"guest-c",status:"RECHAZADA"})]);
assert.equal(union.length,2);
assert.equal(union[0].status,"ACEPTADA","session result must win duplicate");
assert.equal(union[1].status,"RECHAZADA","authorized guest history includes closed rows");
assert.equal(union[1].__guestToken,"second-guest-token");
assert.equal(merge([],[],[]).length,0);
assert.equal(merge([],[{token:""}],[fulfilled(guest)]).length,0,"unproved booking hidden");
assert.equal(merge([],receipts,[fulfilled({id:""}),fulfilled(guest)]).length,1,"missing ids hidden");
const app=fs.readFileSync(path.join(root,"app.js"),"utf8");
const html=fs.readFileSync(path.join(root,"index.html"),"utf8");
const worker=fs.readFileSync(path.join(root,"sw.js"),"utf8");
assert.match(app,/function resetNewTripDraft\(\)/);
const confirmed=app.slice(app.indexOf('function renderBookingSuccess('),app.indexOf('async function submitUrgentPickup()'));
assert.ok(confirmed.includes('resetNewTripDraft();'),"success clears only submitted form");
assert.ok(confirmed.includes('loadTrips({background:true})'),"success refreshes history");
assert.match(app,/function resetSelection\(\)/);
assert.match(app,/function requireAccountForNewTrip\(\)/);
assert.match(app,/if\(!requireAccountForNewTrip\(\)\)return;/);
const urgent=app.slice(app.indexOf("async function submitUrgentPickup()"),app.indexOf("async function submitBooking()"));
const schedule=app.slice(app.indexOf("async function submitBooking()"),app.indexOf("const tripBoard=window.TrasladosTripBoard"));
assert.ok(urgent.indexOf("if(!requireAccountForNewTrip())return")<urgent.indexOf('rpc("customer_request_pickup_fixed_v1"'),"urgent account gate before RPC");
assert.ok(schedule.indexOf("if(!requireAccountForNewTrip())return")<schedule.indexOf('rpc("customer_create_reservation_v12"'),"schedule account gate before RPC");
assert.match(app,/window\.TrasladosGuestHistory\.merge\(rows,guests,result\)/);
assert.match(app,/const guests=jsonStorage\(GUEST_KEY,\[\]\)/);
assert.match(app,/get_reservation_by_token_v5/);
assert.match(app,/customer_list_reservations_v16/);
assert.match(app,/otra app o navegador no se recuperan automáticamente/);
assert.ok(html.indexOf("guest-history.js?v=1")<html.indexOf("app.js?v=80"));
assert.match(worker,/guest-history.js/);
assert.match(worker,/pwa-v80-unificada/);
console.log("OK: session + valid guest union, dedup, closed history, auth safeguards and asset order");
