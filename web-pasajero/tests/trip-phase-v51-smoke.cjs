"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const base=path.join(__dirname,"..");
const read=n=>fs.readFileSync(path.join(base,n),"utf8");
const app=read("app.js"),html=read("index.html"),sw=read("sw.js");
const win={};vm.runInNewContext(read("trip-board.js"),{window:win,Map,Set,Date,Number,Array,String});
const board=win.TrasladosTripBoard;
const accepted={id:"a",code:"TR-A",status:"ACEPTADA",pickup_phase:"SIN_INICIAR",quote_status:"ACEPTADO"};
const moving={...accepted,pickup_phase:"EN_CAMINO",pickup_phase_updated_at:"2026-10-11T12:00:00Z"};
const arrived={...accepted,pickup_phase:"EN_PUNTO",pickup_phase_updated_at:"2026-10-11T12:04:00Z"};
assert.equal(board.metadata(accepted).label,"Confirmada");
assert.equal(board.metadata(moving).label,"Conductor en camino");
assert.equal(board.metadata(arrived).label,"Conductor llegó");
assert.equal(board.metadata(moving).tone,"moving");
assert.equal(board.metadata(arrived).tone,"moving");
assert.equal(board.metadata({...moving,status:"EN_VIAJE"}).label,"En viaje");
const old=board.snapshot([accepted]);
assert.equal(board.notifications(old,[moving]).length,1,"Real phase change alerts while visible");
assert.equal(board.notifications(old,[moving])[0].kind,"state");
assert.equal(board.notifications(board.snapshot([moving]),[moving]).length,0,"Never repeat the same alert");
assert(app.includes('customer_list_reservations_v15'));
assert(app.includes('get_reservation_by_token_v4'));
assert(app.includes('if(r.pickup_phase==="EN_CAMINO")event('));
assert(app.includes('if(r.pickup_phase==="EN_PUNTO")event('));
assert(html.includes('app.js?v=56')&&html.includes('styles.css?v=56')&&html.includes('trip-board.js?v=4'));
assert(sw.includes('traslados-cliente-pwa-v56'));
assert(read("styles.css").includes('.trip-card[data-tone="moving"] .trip-status-dot'));
console.log("PASS v51: authenticated pickup-phase changes drive real moving and arrived badges");
