"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path");
const root=path.join(__dirname,"..");
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const route=read("premium-route.js"),map=read("premium-map.js"),
  app=read("app.js"),css=read("premium-route.css");
assert(route.includes('summary.className="premium-route-summary"'));
assert(route.includes('summary.setAttribute("aria-label","Resumen del viaje")'));
assert(route.includes("PRECIO ORIENTATIVO DEL VIAJE"));
assert(route.includes("DISTANCIA DEL VIAJE"));
assert(route.includes("DURACIÓN ESTIMADA"));
assert(route.includes("Number.isFinite(m.referenceFareUyu)")&&route.includes("A confirmar"));
assert(route.includes("state.metrics")&&route.includes("state.geometry"));
assert(!route.includes("caption.textContent=m.distanceKm"),"No duplicate tiny-line fare caption");
assert(route.includes("Ruta vial verificada, pero sin trazado para dibujar"),"No fake straight-line routes");
assert(route.includes("No pudimos verificar la ruta"),"Explicit provider failure");
assert(route.includes("extraMarkers:stopMarkers"),"Keep selected stops on map");
assert(map.includes('drawMarker(start,"O"')&&map.includes('drawMarker(end,options.routeMode==="pickup"?"P":"D"'),"Map O/D");
assert(map.includes('"#489b80"'),"Non-fluorescent route stroke");
assert(css.includes(".premium-position-metrics{display:none!important}"),"No double pickup km/ETA");
assert(css.includes(".premium-route-summary"),"Price-first layout under map");
assert(app.includes("if(typeof premiumRouteComposer!==\"undefined\")premiumRouteComposer?.sync();\n  roadEngine.estimate"),"Stale fare cleared without breaking standalone booking renderer");
assert(app.includes("roadEngine.verified(data)"),"Only verified route can pass to summary");
assert(app.includes("referenceFareUyu"),"No local invented pricing");
console.log("PASS UX-RECORRIDO-001: no duplicated pickup, verified map O/P/D, price/km/min summary, stale reset");
